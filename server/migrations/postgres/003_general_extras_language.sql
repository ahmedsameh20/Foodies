-- Purely additive: no row is rewritten, no data is translated. See the SQLite file for the meaning of each column.

CREATE TABLE restaurant_extras (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id   BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  name            TEXT NOT NULL,
  name_ar         TEXT,
  name_en         TEXT,
  description_ar  TEXT,
  description_en  TEXT,
  category        TEXT NOT NULL DEFAULT 'other' CHECK (category IN ('drinks','sides','sauces','other')),
  price_cents     BIGINT NOT NULL CHECK (price_cents >= 0),
  image_url       TEXT,
  is_available    BIGINT NOT NULL DEFAULT 1 CHECK (is_available IN (0,1)),
  track_stock     BIGINT NOT NULL DEFAULT 0 CHECK (track_stock IN (0,1)),
  stock_quantity  BIGINT NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
  max_quantity    BIGINT NOT NULL DEFAULT 20 CHECK (max_quantity BETWEEN 1 AND 50),
  sort_order      BIGINT NOT NULL DEFAULT 0,
  created_at      TEXT NOT NULL DEFAULT (iso_now()),
  updated_at      TEXT NOT NULL DEFAULT (iso_now()),
  UNIQUE (id, restaurant_id)
);
CREATE INDEX idx_restaurant_extras_rest ON restaurant_extras(restaurant_id, category, sort_order);

