// Developer tool: derives the PostgreSQL schema from the FINAL state of the SQLite migrations, so the two never drift by hand.
//   node scripts/gen-pg-schema.js > server/migrations/postgres/001_schema.sql
// The output is reviewed and committed; the app never runs this at startup. tests/postgres.test.js compares the resulting PostgreSQL
// tables/columns with SQLite's to catch drift when a new SQLite migration is added (add a matching file under migrations/postgres/).
process.removeAllListeners('warning');
const { openDb, migrate } = require('../server/db');

const db = openDb(':memory:');
migrate(db);
const rows = db.prepare("SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'").all();
// users.restaurant_id -> restaurants and restaurants.owner_id -> users form a cycle: the second is added after both tables exist.
const OWNER_FK = ' REFERENCES users(id) ON DELETE SET NULL';
const tables = rows.filter((r) => r.type === 'table').map((t) => (t.name === 'restaurants' ? { ...t, sql: t.sql.replace(`owner_id INTEGER${OWNER_FK}`, 'owner_id INTEGER') } : t));
const indexes = rows.filter((r) => r.type === 'index');

const ISO = /strftime\('%Y-%m-%dT%H:%M:%fZ','now'\)/g;
function convertTable(sql) {
  return sql
    .replace(/^CREATE TABLE "?(\w+)"?/, 'CREATE TABLE $1')
    .replace(/\bINTEGER PRIMARY KEY\b/g, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\b/g, 'BIGINT')
    .replace(/\bREAL\b/g, 'DOUBLE PRECISION')
    .replace(ISO, 'iso_now()')
    .replace(/(\w+)\s+TEXT NOT NULL UNIQUE COLLATE NOCASE/g, '$1 TEXT NOT NULL')           // case-insensitive uniqueness: see unique index below
    .replace(/(\w+) GLOB '\[0-9\]\[0-9\]\[0-9\]\[0-9\]'/g, (_m, col) => `${col} ~ '^[0-9]{4}$'`);
}
const deps = (sql) => [...sql.matchAll(/REFERENCES\s+"?(\w+)"?/g)].map((m) => m[1]);
const byName = new Map(tables.map((t) => [t.name, t]));
const ordered = [];
const seen = new Set();
const visit = (t) => {
  if (seen.has(t.name)) return;
  seen.add(t.name);
  for (const d of deps(t.sql)) if (d !== t.name && byName.has(d)) visit(byName.get(d));
  ordered.push(t);
};
tables.filter((t) => t.name !== 'schema_migrations').sort((a, b) => a.name.localeCompare(b.name)).forEach(visit);

const out = [];
out.push(`-- PostgreSQL schema: FINAL state equivalent to SQLite migrations 001-005.
-- Generated by scripts/gen-pg-schema.js, then reviewed. Money is BIGINT minor units (never floating point); timestamps are
-- ISO-8601 UTC TEXT exactly as in SQLite so both engines return identical values; booleans are 0/1 BIGINT with CHECKs.
CREATE OR REPLACE FUNCTION iso_now() RETURNS text LANGUAGE sql STABLE AS
$$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') $$;
`);
for (const t of ordered) out.push(`${convertTable(t.sql)};\n`);
out.push('ALTER TABLE restaurants ADD CONSTRAINT fk_restaurants_owner FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE SET NULL;\n');
out.push('-- case-insensitive unique email (SQLite: COLLATE NOCASE). The application also lower-cases emails.\nCREATE UNIQUE INDEX uq_users_email_ci ON users (lower(email));\n');
for (const i of indexes) out.push(`${i.sql.replace(/\bINTEGER\b/g, 'BIGINT')};`);

// triggers: SQLite "AFTER UPDATE ... WHEN NEW.updated_at IS OLD.updated_at" becomes one BEFORE UPDATE function
const withUpdated = rows.filter((r) => r.type === 'trigger' && /_updated$/.test(r.name)).map((r) => r.tbl_name);
out.push(`
CREATE OR REPLACE FUNCTION touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN NEW.updated_at := iso_now(); END IF;
  RETURN NEW;
END $$;`);
for (const t of withUpdated) out.push(`CREATE TRIGGER trg_${t}_updated BEFORE UPDATE ON ${t} FOR EACH ROW EXECUTE FUNCTION touch_updated_at();`);
out.push(`
CREATE OR REPLACE FUNCTION ledger_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'ledger entries are append-only' USING ERRCODE = '23514'; END $$;
CREATE TRIGGER trg_ledger_no_delete BEFORE DELETE ON ledger_entries FOR EACH ROW EXECUTE FUNCTION ledger_append_only();
`);
process.stdout.write(out.join('\n'));
